use std::collections::BTreeMap;
use std::path::PathBuf;

use serde::{Deserialize, Serialize};

use super::ProjectDir;
use crate::board::{Arch, ResolutionSource};
use crate::error::Result;
use crate::fsutil;

pub const STATE_SCHEMA: u32 = 1;
pub const STATE_FILE: &str = "state.json";

/// What the last successful `zem sync` resolved. `west`/`run`/`env` read this instead of
/// re-resolving, and compare `config_hash` to detect a stale sync.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ProjectState {
    pub schema: u32,
    pub zem_version: String,
    pub config_hash: String,
    pub zem_home: PathBuf,
    pub target: TargetState,
    pub workspace: StoreRef,
    pub zephyr_base: PathBuf,
    /// Modules this project builds with (not the whole shared workspace).
    pub modules: BTreeMap<String, PathBuf>,
    pub venv: StoreRef,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub sdk: Option<StoreRef>,
    pub synced_at: u64,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct TargetState {
    pub board: String,
    pub soc: String,
    pub arch: Arch,
    pub toolchains: Vec<String>,
    pub source: ResolutionSource,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct StoreRef {
    pub key: String,
    pub path: PathBuf,
}

impl ProjectDir {
    /// Create `.zem/`, ignored by git as a whole so nothing in it is ever committed.
    pub fn ensure_state_dir(&self) -> Result<PathBuf> {
        let dir = self.state_dir();
        fsutil::create_dir_all(&dir)?;
        let gitignore = dir.join(".gitignore");
        if !gitignore.is_file() {
            fsutil::atomic_write(&gitignore, b"# Generated by zem\n*\n")?;
        }
        Ok(dir)
    }

    pub fn log_path(&self, command: &str) -> PathBuf {
        self.state_dir()
            .join("logs")
            .join(format!("{command}-last.log"))
    }

    pub fn state_path(&self) -> PathBuf {
        self.state_dir().join(STATE_FILE)
    }

    pub fn read_state(&self) -> Result<Option<ProjectState>> {
        fsutil::read_json(&self.state_path())
    }

    pub fn write_state(&self, state: &ProjectState) -> Result<()> {
        fsutil::write_json(&self.state_path(), state)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::home::ZemHome;

    #[test]
    fn state_round_trips_and_dir_is_ignored() {
        let tmp = tempfile::tempdir().unwrap();
        let home = ZemHome::new(tmp.path().join("zh"));
        let project = ProjectDir::new(tmp.path(), &home).unwrap();
        project.ensure_state_dir().unwrap();
        let ignore = std::fs::read_to_string(project.state_dir().join(".gitignore")).unwrap();
        assert!(ignore.lines().any(|l| l == "*"));

        let state = ProjectState {
            schema: STATE_SCHEMA,
            zem_version: "0.1.0".into(),
            config_hash: "abc".into(),
            zem_home: home.root().to_path_buf(),
            target: TargetState {
                board: "esp32c3_devkitm".into(),
                soc: "esp32c3".into(),
                arch: Arch::Riscv,
                toolchains: vec!["riscv64-zephyr-elf".into()],
                source: ResolutionSource::BoardYml,
            },
            workspace: StoreRef {
                key: "zephyr-v4.2.0-x".into(),
                path: "/zh/workspaces/zephyr-v4.2.0-x".into(),
            },
            zephyr_base: "/zh/workspaces/zephyr-v4.2.0-x/zephyr".into(),
            modules: BTreeMap::from([(
                "hal_espressif".into(),
                "/zh/w/modules/hal/espressif".into(),
            )]),
            venv: StoreRef {
                key: "py3.12-x".into(),
                path: "/zh/venvs/py3.12-x".into(),
            },
            sdk: None,
            synced_at: 0,
        };
        project.write_state(&state).unwrap();
        assert_eq!(project.read_state().unwrap(), Some(state));
    }
}
