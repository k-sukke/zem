//! The project's own west configuration, used through `WEST_CONFIG_LOCAL` instead of the shared
//! workspace's `.west/config`, so plain `west build` / `west flash` pick up this project's board,
//! modules and build directory.

use std::path::Path;

use crate::manifest::MANIFEST_DIR;
use crate::platform;

pub const WEST_CONFIG_FILE: &str = "west-config";

pub struct WestConfigInputs<'a> {
    pub board: &'a str,
    pub modules: Vec<&'a str>,
    pub build_dir: &'a Path,
    pub user_cache_dir: &'a Path,
    pub cmake_args: &'a [String],
}

pub fn render(c: &WestConfigInputs<'_>) -> String {
    // Every other project in the shared workspace is inactive, which also keeps it out of
    // Zephyr's module list.
    let mut filter = vec!["-.*".to_string(), "+zephyr".to_string()];
    filter.extend(c.modules.iter().map(|m| format!("+{}", regex_escape(m))));

    let mut cmake_args = vec![
        format!(
            "-DUSER_CACHE_DIR={}",
            platform::to_cmake_path(c.user_cache_dir)
        ),
        "-DCMAKE_FIND_USE_PACKAGE_REGISTRY=OFF".to_string(),
    ];
    cmake_args.extend(c.cmake_args.iter().cloned());
    let cmake_args: Vec<String> = cmake_args.iter().map(|a| shell_quote(a)).collect();

    let dir_fmt = c
        .build_dir
        .to_string_lossy()
        .replace('{', "{{")
        .replace('}', "}}");

    format!(
        "# Generated by zem from zem.toml; edits are overwritten.\n\
         [manifest]\n\
         path = {MANIFEST_DIR}\n\
         file = west.yml\n\
         project-filter = {filter}\n\
         \n\
         [zephyr]\n\
         base = zephyr\n\
         \n\
         [build]\n\
         board = {board}\n\
         dir-fmt = {dir_fmt}\n\
         cmake-args = {cmake_args}\n",
        filter = ini_escape(&filter.join(",")),
        board = build_value(c.board),
        dir_fmt = build_value(&dir_fmt),
        cmake_args = build_value(&cmake_args.join(" ")),
    )
}

/// west reads its configuration with `configparser`'s `%` interpolation.
fn ini_escape(s: &str) -> String {
    s.replace('%', "%%")
}

/// `build.*` is read by Zephyr's west extensions through west's legacy configparser, which
/// receives already-interpolated values and interpolates them again.
fn build_value(s: &str) -> String {
    ini_escape(&ini_escape(s))
}

fn regex_escape(s: &str) -> String {
    s.chars()
        .flat_map(|c| {
            let escape = !(c.is_ascii_alphanumeric() || c == '_' || c == '-');
            escape.then_some('\\').into_iter().chain([c])
        })
        .collect()
}

/// `cmake-args` is split with Python's `shlex.split`.
fn shell_quote(s: &str) -> String {
    if !s.is_empty()
        && s.chars()
            .all(|c| c.is_ascii_alphanumeric() || "-_=./:;,+@".contains(c))
    {
        s.to_string()
    } else {
        format!("'{}'", s.replace('\'', r"'\''"))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn renders_project_scoped_config() {
        let cmake = ["-DCONF_FILE=prj.conf".to_string(), "-DNAME=a b".to_string()];
        let text = render(&WestConfigInputs {
            board: "esp32s3_devkitc/esp32s3/procpu",
            modules: vec!["hal_espressif", "mbedtls"],
            build_dir: Path::new("/p/100%/{x}/build"),
            user_cache_dir: Path::new("/zh/cache/zephyr"),
            cmake_args: &cmake,
        });
        assert!(text.contains("project-filter = -.*,+zephyr,+hal_espressif,+mbedtls\n"));
        assert!(text.contains("board = esp32s3_devkitc/esp32s3/procpu\n"));
        assert!(text.contains("dir-fmt = /p/100%%%%/{{x}}/build\n"));
        assert!(text.contains(
            "cmake-args = -DUSER_CACHE_DIR=/zh/cache/zephyr \
             -DCMAKE_FIND_USE_PACKAGE_REGISTRY=OFF -DCONF_FILE=prj.conf '-DNAME=a b'\n"
        ));
    }

    /// configparser's `BasicInterpolation`: `%%` is a literal `%`, a lone `%` is an error.
    fn interpolate(s: &str) -> Option<String> {
        let mut out = String::new();
        let mut chars = s.chars();
        while let Some(c) = chars.next() {
            if c == '%' && chars.next()? != '%' {
                return None;
            }
            out.push(c);
        }
        Some(out)
    }

    fn value<'t>(text: &'t str, key: &str) -> &'t str {
        text.lines()
            .find_map(|l| l.strip_prefix(&format!("{key} = ")))
            .unwrap()
    }

    #[test]
    fn percent_survives_wests_reads() {
        let cmake = ["-DX=50%".to_string()];
        let text = render(&WestConfigInputs {
            board: "b",
            modules: vec!["hal_espressif"],
            build_dir: Path::new("/p/100%/build"),
            user_cache_dir: Path::new("/zh/%cache"),
            cmake_args: &cmake,
        });
        let legacy = |key| interpolate(&interpolate(value(&text, key)).unwrap()).unwrap();
        assert_eq!(legacy("dir-fmt"), "/p/100%/build");
        assert_eq!(
            legacy("cmake-args"),
            "'-DUSER_CACHE_DIR=/zh/%cache' -DCMAKE_FIND_USE_PACKAGE_REGISTRY=OFF '-DX=50%'"
        );
        for key in ["path", "file", "project-filter", "base"] {
            assert!(interpolate(value(&text, key)).is_some(), "{key}");
        }
    }

    #[test]
    fn module_names_are_matched_literally() {
        assert_eq!(regex_escape("hal_nxp"), "hal_nxp");
        assert_eq!(regex_escape("a.b+c"), r"a\.b\+c");
    }
}
