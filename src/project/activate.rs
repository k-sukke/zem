use std::path::Path;

use super::ProjectDir;
use crate::env::shell::{batch_escape, powershell_quote};
use crate::error::Result;
use crate::fsutil;

pub const ACTIVATE_SH: &str = "activate.sh";
pub const ACTIVATE_FISH: &str = "activate.fish";
pub const ACTIVATE_PS1: &str = "activate.ps1";
pub const ACTIVATE_BAT: &str = "activate.bat";

fn sh_quote(s: &str) -> String {
    format!("'{}'", s.replace('\'', r"'\''"))
}

fn fish_quote(s: &str) -> String {
    format!("'{}'", s.replace('\\', r"\\").replace('\'', r"\'"))
}

/// The scripts delegate to `zem env` so they always reflect the current shell's environment;
/// `fallback_exe` is used when `zem` is not on PATH.
pub fn render_sh(root: &Path, fallback_exe: &Path) -> String {
    format!(
        "# Generated by zem. Usage: . .zem/{ACTIVATE_SH}\n\
         if command -v zem >/dev/null 2>&1; then _zem=zem; else _zem={exe}; fi\n\
         eval \"$(\"$_zem\" --project-dir {root} env --shell posix)\"\n\
         unset _zem\n",
        exe = sh_quote(&fallback_exe.to_string_lossy()),
        root = sh_quote(&root.to_string_lossy()),
    )
}

pub fn render_fish(root: &Path, fallback_exe: &Path) -> String {
    format!(
        "# Generated by zem. Usage: source .zem/{ACTIVATE_FISH}\n\
         set -l _zem {exe}\n\
         type -q zem; and set _zem zem\n\
         $_zem --project-dir {root} env --shell fish | source\n",
        exe = fish_quote(&fallback_exe.to_string_lossy()),
        root = fish_quote(&root.to_string_lossy()),
    )
}

/// Run `zem env` and apply its output. PowerShell decodes a native program's output with
/// `[Console]::OutputEncoding`, often a legacy code page (e.g. 932), while zem writes UTF-8;
/// switch to UTF-8 for the call so non-ASCII paths survive, and restore it afterwards.
/// PowerShell pipes the output line by line; `Out-String` joins it into one script.
fn powershell_apply(exe: &str, root: &Path) -> String {
    format!(
        "$__zem_enc = [Console]::OutputEncoding\n\
         try {{\n\
         \x20   [Console]::OutputEncoding = [Text.UTF8Encoding]::new($false)\n\
         \x20   $__zem_out = & {exe} --project-dir {root} env --shell powershell | Out-String\n\
         }} finally {{\n\
         \x20   [Console]::OutputEncoding = $__zem_enc\n\
         }}\n\
         if ($__zem_out) {{ Invoke-Expression $__zem_out }}\n\
         Remove-Variable __zem_enc, __zem_out\n",
        root = powershell_quote(&root.to_string_lossy()),
    )
}

pub fn render_ps1(root: &Path, fallback_exe: &Path) -> String {
    format!(
        "# Generated by zem. Usage: . .zem\\{ACTIVATE_PS1}\n\
         $_zem = {exe}\n\
         if (Get-Command zem -CommandType Application -ErrorAction SilentlyContinue) {{ $_zem = 'zem' }}\n\
         {apply}\
         Remove-Variable _zem\n",
        exe = powershell_quote(&fallback_exe.to_string_lossy()),
        apply = powershell_apply("$_zem", root),
    )
}

/// cmd cannot capture a command's output into the current shell except through a file, so
/// the script writes `zem env --shell cmd` to a temporary batch file and `call`s it. Every
/// line starts with `@` instead of `echo off`, which would leak into the interactive prompt.
pub fn render_bat(root: &Path, fallback_exe: &Path) -> String {
    format!(
        "@rem Generated by zem. Usage: .zem\\{ACTIVATE_BAT}\r\n\
         @set \"_zem={exe}\"\r\n\
         @where /q zem && set \"_zem=zem\"\r\n\
         @set \"_zem_env=%TEMP%\\zem-env-%RANDOM%%RANDOM%.bat\"\r\n\
         @\"%_zem%\" --project-dir \"{root}\" env --shell cmd > \"%_zem_env%\" && call \"%_zem_env%\"\r\n\
         @del \"%_zem_env%\" 2>nul\r\n\
         @set \"_zem=\" & set \"_zem_env=\"\r\n",
        exe = batch_escape(&fallback_exe.to_string_lossy()),
        root = batch_escape(&root.to_string_lossy()),
    )
}

/// `-Command` script for `zem shell` with PowerShell. It runs after the user's profile, so
/// PATH changes made there cannot shadow the zem tools, and prefixes the existing prompt.
pub fn powershell_init_command(root: &Path, exe: &Path, prompt: &str) -> String {
    format!(
        "{apply}\
         $global:__zem_prompt = $function:prompt\n\
         function global:prompt {{ {prompt} + (& $global:__zem_prompt) }}\n",
        apply = powershell_apply(&powershell_quote(&exe.to_string_lossy()), root),
        prompt = powershell_quote(prompt),
    )
}

/// `-EncodedCommand` takes base64 of UTF-16LE, which sidesteps Windows command-line quoting.
pub fn powershell_encode(script: &str) -> String {
    const ALPHABET: &[u8; 64] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    let bytes: Vec<u8> = script.encode_utf16().flat_map(u16::to_le_bytes).collect();
    let mut out = String::with_capacity(bytes.len().div_ceil(3) * 4);
    for chunk in bytes.chunks(3) {
        let n = chunk
            .iter()
            .enumerate()
            .fold(0u32, |acc, (i, &b)| acc | (u32::from(b) << (16 - 8 * i)));
        for i in 0..4 {
            if i <= chunk.len() {
                out.push(ALPHABET[(n >> (18 - 6 * i)) as usize & 63] as char);
            } else {
                out.push('=');
            }
        }
    }
    out
}

/// `zem env` invocation for `zem shell` startup files, run after the user's own rc files so
/// PATH changes made there (pyenv, conda, ...) cannot shadow the zem tools.
fn reapply_sh(root: &Path, exe: &Path, prompt: &str) -> String {
    format!(
        "eval \"$({exe} --project-dir {root} env --shell posix)\"\n\
         PS1={prompt}\"$PS1\"\n",
        exe = sh_quote(&exe.to_string_lossy()),
        root = sh_quote(&root.to_string_lossy()),
        prompt = sh_quote(prompt),
    )
}

/// zsh reads `$ZDOTDIR/.zshenv` and `.zshrc`; these run the user's files from
/// `$ZEM_USER_ZDOTDIR` and then restore `ZDOTDIR` for the rest of the session.
pub fn render_zshenv(own_dir: &Path) -> String {
    format!(
        "# Generated by zem for `zem shell`\n\
         ZDOTDIR=\"${{ZEM_USER_ZDOTDIR:-$HOME}}\"\n\
         [ -r \"$ZDOTDIR/.zshenv\" ] && . \"$ZDOTDIR/.zshenv\"\n\
         ZEM_USER_ZDOTDIR=\"$ZDOTDIR\"\n\
         ZDOTDIR={own}\n",
        own = sh_quote(&own_dir.to_string_lossy()),
    )
}

pub fn render_zshrc(root: &Path, exe: &Path, prompt: &str) -> String {
    format!(
        "# Generated by zem for `zem shell`\n\
         ZDOTDIR=\"$ZEM_USER_ZDOTDIR\"\n\
         unset ZEM_USER_ZDOTDIR\n\
         [ -r \"$ZDOTDIR/.zshrc\" ] && . \"$ZDOTDIR/.zshrc\"\n\
         {}",
        reapply_sh(root, exe, prompt)
    )
}

pub fn render_bashrc(root: &Path, exe: &Path, prompt: &str) -> String {
    format!(
        "# Generated by zem for `zem shell`\n\
         [ -r \"$HOME/.bashrc\" ] && . \"$HOME/.bashrc\"\n\
         {}",
        reapply_sh(root, exe, prompt)
    )
}

/// fish runs `-C` commands after its config files.
pub fn fish_init_command(root: &Path, exe: &Path) -> String {
    format!(
        "{} --project-dir {} env --shell fish | source",
        fish_quote(&exe.to_string_lossy()),
        fish_quote(&root.to_string_lossy())
    )
}

impl ProjectDir {
    pub fn write_activate_scripts(&self, zem_exe: &Path) -> Result<()> {
        let dir = self.state_dir();
        fsutil::atomic_write(
            &dir.join(ACTIVATE_SH),
            render_sh(self.root(), zem_exe).as_bytes(),
        )?;
        fsutil::atomic_write(
            &dir.join(ACTIVATE_FISH),
            render_fish(self.root(), zem_exe).as_bytes(),
        )?;
        fsutil::atomic_write(
            &dir.join(ACTIVATE_PS1),
            render_ps1(self.root(), zem_exe).as_bytes(),
        )?;
        fsutil::atomic_write(
            &dir.join(ACTIVATE_BAT),
            render_bat(self.root(), zem_exe).as_bytes(),
        )
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn scripts_quote_paths() {
        let sh = render_sh(Path::new("/p/it's"), Path::new("/bin/zem"));
        assert!(
            sh.contains(r"--project-dir '/p/it'\''s' env --shell posix"),
            "{sh}"
        );
        assert!(sh.contains("_zem='/bin/zem'"));
        let fish = render_fish(Path::new("/p/it's"), Path::new("/bin/zem"));
        assert!(
            fish.contains(r"--project-dir '/p/it\'s' env --shell fish | source"),
            "{fish}"
        );
    }

    #[test]
    fn shell_rc_files_source_user_files_before_reapplying() {
        let rc = render_zshrc(Path::new("/p"), Path::new("/bin/zem"), "(zem:demo) ");
        let user = rc.find(".zshrc\"").unwrap();
        let eval = rc
            .find("eval \"$('/bin/zem' --project-dir '/p' env --shell posix)\"")
            .unwrap();
        assert!(user < eval, "{rc}");
        assert!(rc.ends_with("PS1='(zem:demo) '\"$PS1\"\n"), "{rc}");
        let env = render_zshenv(Path::new("/p/.zem/shell/zsh"));
        assert!(env.ends_with("ZDOTDIR='/p/.zem/shell/zsh'\n"), "{env}");
        assert!(
            render_bashrc(Path::new("/p"), Path::new("/bin/zem"), "x")
                .contains(". \"$HOME/.bashrc\"")
        );
    }

    #[test]
    fn windows_scripts_quote_paths() {
        let ps1 = render_ps1(Path::new(r"C:\p\it's"), Path::new(r"C:\bin\zem.exe"));
        assert!(ps1.contains(r"$_zem = 'C:\bin\zem.exe'"), "{ps1}");
        assert!(
            ps1.contains(r"& $_zem --project-dir 'C:\p\it''s' env --shell powershell"),
            "{ps1}"
        );
        let bat = render_bat(Path::new(r"C:\p\100%"), Path::new(r"C:\bin\zem.exe"));
        assert!(bat.contains(r#"@set "_zem=C:\bin\zem.exe""#), "{bat}");
        assert!(
            bat.contains(r#"--project-dir "C:\p\100%%" env --shell cmd"#),
            "{bat}"
        );
        assert!(bat.lines().all(|l| l.starts_with('@')), "{bat}");
    }

    #[test]
    fn powershell_reads_zem_output_as_utf8_and_restores_the_encoding() {
        let ps1 = render_ps1(Path::new(r"C:\p"), Path::new(r"C:\zem.exe"));
        let set = ps1
            .find("[Console]::OutputEncoding = [Text.UTF8Encoding]::new($false)")
            .unwrap();
        let call = ps1.find("$__zem_out = & $_zem").unwrap();
        let restore = ps1.find("[Console]::OutputEncoding = $__zem_enc").unwrap();
        let apply = ps1.find("Invoke-Expression $__zem_out").unwrap();
        assert!(set < call && call < restore && restore < apply, "{ps1}");
    }

    #[test]
    fn powershell_prompt_wraps_the_existing_one() {
        let init =
            powershell_init_command(Path::new(r"C:\p"), Path::new(r"C:\zem.exe"), "(zem:demo) ");
        assert!(
            init.contains("$__zem_out = & 'C:\\zem.exe' --project-dir 'C:\\p' env"),
            "{init}"
        );
        assert!(
            init.contains("function global:prompt { '(zem:demo) ' + (& $global:__zem_prompt) }"),
            "{init}"
        );
    }

    #[test]
    fn encodes_utf16le_base64() {
        // [Convert]::ToBase64String([Text.Encoding]::Unicode.GetBytes('dir'))
        assert_eq!(powershell_encode("dir"), "ZABpAHIA");
        assert_eq!(powershell_encode("ab"), "YQBiAA==");
        assert_eq!(powershell_encode(""), "");
    }
}
