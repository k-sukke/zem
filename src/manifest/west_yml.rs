use std::collections::BTreeSet;
use std::fmt::Write as _;

/// Input for the minimal west manifest of a shared workspace.
pub struct WestManifest<'a> {
    pub zephyr_url: &'a str,
    pub revision: &'a str,
    /// Shallow-clone zephyr; only safe for immutable revisions such as release tags.
    pub shallow: bool,
    /// Union of the modules required by every project using this workspace.
    pub modules: &'a BTreeSet<String>,
}

pub const MANIFEST_DIR: &str = "manifest";

pub fn render(m: &WestManifest<'_>) -> String {
    let mut out = String::new();
    out.push_str("# Generated by zem. Do not edit: changes are overwritten by `zem sync`.\n");
    out.push_str("manifest:\n  version: \"1.2\"\n  projects:\n    - name: zephyr\n");
    let _ = writeln!(out, "      url: {}", quote(m.zephyr_url));
    let _ = writeln!(out, "      revision: {}", quote(m.revision));
    if m.shallow {
        out.push_str("      clone-depth: 1\n");
    }
    out.push_str("      import:\n        name-allowlist:\n");
    for module in m.modules {
        let _ = writeln!(out, "          - {}", quote(module));
    }
    let _ = write!(out, "  self:\n    path: {MANIFEST_DIR}\n");
    out
}

/// JSON strings are valid double-quoted YAML scalars.
fn quote(s: &str) -> String {
    serde_json::to_string(s).unwrap_or_else(|_| format!("\"{s}\""))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn modules(names: &[&str]) -> BTreeSet<String> {
        names.iter().map(|s| s.to_string()).collect()
    }

    #[test]
    fn renders_tag_manifest() {
        let mods = modules(&["mbedtls", "hal_espressif"]);
        let text = render(&WestManifest {
            zephyr_url: "https://github.com/zephyrproject-rtos/zephyr",
            revision: "v4.2.0",
            shallow: true,
            modules: &mods,
        });
        insta::assert_snapshot!(text);
    }

    #[test]
    fn sha_manifest_is_not_shallow_and_parses() {
        let mods = modules(&["hal_espressif"]);
        let text = render(&WestManifest {
            zephyr_url: "https://example.com/fork/zephyr",
            revision: &"a".repeat(40),
            shallow: false,
            modules: &mods,
        });
        assert!(!text.contains("clone-depth"));
        let value: serde_yaml_ng::Value = serde_yaml_ng::from_str(&text).unwrap();
        let project = &value["manifest"]["projects"][0];
        assert_eq!(project["revision"].as_str(), Some("a".repeat(40).as_str()));
        assert_eq!(
            project["import"]["name-allowlist"][0].as_str(),
            Some("hal_espressif")
        );
        assert_eq!(
            value["manifest"]["self"]["path"].as_str(),
            Some(MANIFEST_DIR)
        );
    }
}
