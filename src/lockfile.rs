//! `zem.lock`: the exact Zephyr commit, module SHAs, SDK version and Python packages a sync
//! produced, committed next to `zem.toml` so `zem sync --locked` reproduces them elsewhere.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

use console::style;
use serde::{Deserialize, Serialize};

use crate::config::{Python, SdkVersion, ZemConfig};
use crate::error::{Result, ZemError};
use crate::fsutil;
use crate::home::keys::{normalize_git_url, sha256_hex};

pub const LOCK_FILE: &str = "zem.lock";
pub const LOCK_VERSION: u32 = 1;

const HEADER: &str = "# Generated by `zem sync`. Commit this file; do not edit it by hand.\n\n";

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Lockfile {
    pub version: u32,
    pub zephyr: ZephyrLock,
    #[serde(default)]
    pub modules: BTreeMap<String, String>,
    pub sdk: SdkLock,
    pub python: PythonLock,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct ZephyrLock {
    pub url: String,
    pub revision: String,
    pub commit: String,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct SdkLock {
    pub version: String,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields, rename_all = "kebab-case")]
pub struct PythonLock {
    pub version: String,
    #[serde(default)]
    pub extra_requirements: Vec<String>,
    pub packages: Vec<String>,
}

pub fn path(root: &Path) -> PathBuf {
    root.join(LOCK_FILE)
}

pub fn read(root: &Path) -> Result<Option<Lockfile>> {
    let path = path(root);
    let text = match std::fs::read_to_string(&path) {
        Ok(text) => text,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(None),
        Err(e) => return Err(ZemError::io(&path)(e)),
    };
    let invalid = |message: String| ZemError::LockInvalid {
        path: path.clone(),
        message,
    };
    let lock: Lockfile = toml::from_str(&text).map_err(|e| invalid(e.message().to_string()))?;
    if lock.version != LOCK_VERSION {
        return Err(invalid(format!(
            "unsupported version {} (this zem understands {LOCK_VERSION})",
            lock.version
        )));
    }
    Ok(Some(lock))
}

pub fn write(root: &Path, lock: &Lockfile) -> Result<()> {
    let body = toml::to_string_pretty(lock).expect("lockfile serializes");
    fsutil::atomic_write(&path(root), format!("{HEADER}{body}").as_bytes())
}

fn normalized_extras(extras: &[String]) -> Vec<String> {
    let mut extras: Vec<String> = extras.iter().map(|r| r.trim().to_string()).collect();
    extras.sort();
    extras.dedup();
    extras
}

impl ZephyrLock {
    pub fn matches(&self, cfg: &ZemConfig) -> bool {
        normalize_git_url(&self.url) == normalize_git_url(&cfg.zephyr.url)
            && self.revision == cfg.zephyr.version.trim()
    }
}

impl PythonLock {
    pub fn new(cfg: &Python, packages: Vec<String>) -> Self {
        PythonLock {
            version: cfg.version.trim().to_string(),
            extra_requirements: normalized_extras(&cfg.extra_requirements),
            packages,
        }
    }

    pub fn matches(&self, cfg: &Python) -> bool {
        self.version == cfg.version.trim()
            && self.extra_requirements == normalized_extras(&cfg.extra_requirements)
    }
}

/// Stable identity of a frozen package set, used to pick a venv that has exactly these pins.
pub fn packages_digest(packages: &[String]) -> String {
    sha256_hex(format!("zem-packages-v1\0{}", packages.join("\n")).as_bytes())
}

/// `uv pip freeze` output reduced to sorted `name==version` pins usable as a constraints file.
pub fn parse_freeze(out: &str) -> Vec<String> {
    let mut pins: Vec<String> = out
        .lines()
        .map(str::trim)
        .filter(|l| !l.starts_with('#') && l.contains("=="))
        .map(str::to_string)
        .collect();
    pins.sort_by_key(|p| p.to_ascii_lowercase());
    pins.dedup();
    pins
}

/// The parts of an existing `zem.lock` that still apply to `zem.toml`.
#[derive(Debug, Clone, Default)]
pub struct Pins {
    pub locked: bool,
    pub commit: Option<String>,
    pub modules: BTreeMap<String, String>,
    pub sdk: Option<String>,
    pub packages: Option<Vec<String>>,
}

impl Pins {
    /// With `locked`, a missing or outdated lock is an error instead of being ignored.
    pub fn new(lock: Option<&Lockfile>, cfg: &ZemConfig, locked: bool) -> Result<Self> {
        let stale = |reason: &str| -> Result<()> {
            if locked {
                Err(ZemError::LockStale {
                    reason: reason.to_string(),
                })
            } else {
                Ok(())
            }
        };
        let Some(lock) = lock else {
            if locked {
                return Err(ZemError::LockMissing);
            }
            return Ok(Pins::default());
        };
        let mut pins = Pins {
            locked,
            ..Pins::default()
        };
        if !lock.zephyr.matches(cfg) {
            stale("[zephyr] url or version changed")?;
            return Ok(pins);
        }
        pins.commit = Some(lock.zephyr.commit.clone());
        pins.modules = lock.modules.clone();
        match &cfg.sdk.version {
            SdkVersion::Exact(v) if *v != lock.sdk.version => stale("[sdk].version changed")?,
            _ => pins.sdk = Some(lock.sdk.version.clone()),
        }
        if lock.python.matches(&cfg.python) {
            pins.packages = Some(lock.python.packages.clone());
        } else {
            stale("[python] settings changed")?;
        }
        Ok(pins)
    }

    /// Compare what sync produced against the lock: an error with `--locked`, else a warning.
    pub fn verify(&self, what: &str, locked: Option<&str>, actual: &str) -> Result<()> {
        let Some(expected) = locked else {
            if self.locked {
                return Err(ZemError::LockStale {
                    reason: format!("{what} is not pinned"),
                });
            }
            return Ok(());
        };
        if expected == actual {
            return Ok(());
        }
        if self.locked {
            return Err(ZemError::LockMismatch {
                what: what.to_string(),
                expected: expected.to_string(),
                actual: actual.to_string(),
            });
        }
        eprintln!(
            "      {} {what} differs from zem.lock ({expected} → {actual}); updating the lock",
            style("warning:").yellow().bold()
        );
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::config::{Project, Target, Zephyr};

    fn config() -> ZemConfig {
        ZemConfig {
            schema: 1,
            project: Project { name: "p".into() },
            zephyr: Zephyr {
                version: "v4.2.0".into(),
                url: "https://github.com/zephyrproject-rtos/zephyr".into(),
            },
            target: Target {
                board: "esp32c3_devkitm".into(),
                arch: None,
            },
            modules: Default::default(),
            blobs: Default::default(),
            sdk: Default::default(),
            python: Default::default(),
            build: Default::default(),
            env: Default::default(),
        }
    }

    fn lock(cfg: &ZemConfig) -> Lockfile {
        Lockfile {
            version: LOCK_VERSION,
            zephyr: ZephyrLock {
                url: format!("{}.git", cfg.zephyr.url),
                revision: cfg.zephyr.version.clone(),
                commit: "413b789deb391d3a37d06b463288a5fe765ee57e".into(),
            },
            modules: BTreeMap::from([("hal_espressif".into(), "f3453bde".into())]),
            sdk: SdkLock {
                version: "0.17.2".into(),
            },
            python: PythonLock::new(
                &cfg.python,
                vec!["pyyaml==6.0.2".into(), "west==1.4.0".into()],
            ),
        }
    }

    #[test]
    fn round_trips_through_toml() {
        let dir = tempfile::tempdir().unwrap();
        let lock = lock(&config());
        write(dir.path(), &lock).unwrap();
        let text = std::fs::read_to_string(path(dir.path())).unwrap();
        assert!(text.starts_with("# Generated by `zem sync`"));
        assert!(text.contains("\n    \"west==1.4.0\",\n]"), "{text}");
        assert_eq!(read(dir.path()).unwrap(), Some(lock));
    }

    #[test]
    fn rejects_unknown_versions() {
        let dir = tempfile::tempdir().unwrap();
        let mut lock = lock(&config());
        lock.version = 99;
        write(dir.path(), &lock).unwrap();
        assert!(matches!(
            read(dir.path()),
            Err(ZemError::LockInvalid { .. })
        ));
    }

    #[test]
    fn matching_lock_pins_everything() {
        let cfg = config();
        let pins = Pins::new(Some(&lock(&cfg)), &cfg, true).unwrap();
        assert_eq!(
            pins.commit.as_deref(),
            Some("413b789deb391d3a37d06b463288a5fe765ee57e")
        );
        assert_eq!(pins.sdk.as_deref(), Some("0.17.2"));
        assert_eq!(pins.packages.unwrap().len(), 2);
    }

    #[test]
    fn stale_sections_are_dropped_or_rejected() {
        let mut cfg = config();
        let lock = lock(&cfg);
        cfg.python.extra_requirements = vec!["pytest".into()];
        let pins = Pins::new(Some(&lock), &cfg, false).unwrap();
        assert!(pins.commit.is_some());
        assert!(pins.packages.is_none());
        assert!(matches!(
            Pins::new(Some(&lock), &cfg, true),
            Err(ZemError::LockStale { .. })
        ));

        cfg.zephyr.version = "v4.1.0".into();
        let pins = Pins::new(Some(&lock), &cfg, false).unwrap();
        assert!(pins.commit.is_none() && pins.modules.is_empty());
        assert!(matches!(
            Pins::new(None, &cfg, true),
            Err(ZemError::LockMissing)
        ));
    }

    #[test]
    fn verify_errors_only_when_locked() {
        let loose = Pins::default();
        assert!(loose.verify("zephyr", Some("a"), "b").is_ok());
        assert!(loose.verify("zephyr", None, "b").is_ok());
        let strict = Pins {
            locked: true,
            ..Pins::default()
        };
        assert!(strict.verify("zephyr", Some("a"), "a").is_ok());
        assert!(matches!(
            strict.verify("zephyr", Some("a"), "b"),
            Err(ZemError::LockMismatch { .. })
        ));
        assert!(matches!(
            strict.verify("module lvgl", None, "b"),
            Err(ZemError::LockStale { .. })
        ));
    }

    #[test]
    fn freeze_output_becomes_sorted_pins() {
        let out = "PyYAML==6.0.2\n# comment\nanytree==2.13.0\n-e file:///x\nwest==1.4.0\n";
        assert_eq!(
            parse_freeze(out),
            ["anytree==2.13.0", "PyYAML==6.0.2", "west==1.4.0"]
        );
    }
}
